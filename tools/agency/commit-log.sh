#!/usr/bin/env bash
# commit-log.sh [range] > docs/history/COMMIT-LOG.md : every commit, oldest first, with its full message and the files
# it touched. Default range: the whole history of the current branch.
set -euo pipefail
range="${1:-HEAD}"
echo "# Commit log"
echo
echo "Every commit on \`$(git rev-parse --abbrev-ref HEAD)\` up to \`$(git rev-parse --short HEAD)\`, oldest first, with its full message and"
echo "a summary of the files it changed. Generated by \`tools/agency/commit-log.sh\`; regenerate rather than edit."
echo
git log --reverse --date=iso-strict --format='%x1e%h%x1f%ad%x1f%an%x1f%P%x1f%B' --stat=160 "$range" | python3 -c '
import sys
data = sys.stdin.read().split("\x1e")[1:]
for i, chunk in enumerate(data, 1):
    head, _, rest = chunk.partition("\x1f")
    date, _, rest = rest.partition("\x1f")
    author, _, rest = rest.partition("\x1f")
    parents, _, rest = rest.partition("\x1f")
    body = rest.rstrip()
    # --stat output follows the message after a blank line; it starts with a space-indented file line
    lines = body.split("\n")
    msg, stat = [], []
    for line in lines:
        (stat if stat or (line.startswith(" ") and "|" in line) else msg).append(line)
    subject = msg[0] if msg else ""
    kind = " (merge)" if len(parents.split()) > 1 else ""
    print(f"## {i}. `{head}` {subject}{kind}")
    print()
    print(f"*{date} · {author}*")
    print()
    rest_msg = "\n".join(msg[1:]).strip()
    if rest_msg:
        print(rest_msg)
        print()
    if stat:
        print("```")
        print("\n".join(s for s in stat if s.strip()))
        print("```")
        print()
'
