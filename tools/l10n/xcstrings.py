#!/usr/bin/env python3
"""Builds String Catalogs (.xcstrings) from the app's .lproj string tables, for the move to String Catalogs.

    python3 tools/l10n/xcstrings.py --check            # build in memory and prove nothing is lost (exit 1 if it is)
    python3 tools/l10n/xcstrings.py --out DIR          # write DIR/Localizable.xcstrings, AppShortcuts.xcstrings and
                                                       # InfoPlist.xcstrings

Every key of every locale's Localizable.strings / .stringsdict, AppShortcuts.strings and InfoPlist.strings becomes
one catalog entry with a localization per locale. Where a locale has a key in both its .strings and its .stringsdict,
the plural wins, as it does at run time. A .stringsdict plural becomes the catalog's plural variations
(a whole-string `%#@n@` rule) or substitutions (a variable inside a longer string). The counted strings in
plurals-en.json get English plural variations as well, so a count of one reads "1 bullseye"; translators then add
the forms their language uses (one, few, many …) in the catalog instead of a flat string. Legacy `timbre_*` keys,
looked up at run time rather than written in code, are marked `manual` so Xcode never flags them stale.

Nothing here edits the app: the catalogs go to --out. Adopting them is one change made when no other work is touching
strings: write them into ios/Timbre/Resources, delete the .lproj Localizable / AppShortcuts / InfoPlist tables, point
the widget and watch targets in ios/project.yml at Localizable.xcstrings, and switch apply.py and report.py to read
and write the catalog (Learn.strings, generated by tools/curriculum, stays a .strings table).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import report  # noqa: E402

TABLES = ("Localizable", "AppShortcuts", "InfoPlist")
PLURALS_EN = HERE / "plurals-en.json"
VARIABLE = re.compile(r"%(?:(\d+)\$)?#@(\w+)@")
FORMS = ("zero", "one", "two", "few", "many", "other")


def unit(value: str) -> dict:
    return {"stringUnit": {"state": "translated", "value": value}}


def plural_variations(forms: dict) -> dict:
    return {"plural": {form: unit(forms[form]) for form in FORMS if form in forms}}


def from_stringsdict(entry: dict) -> dict:
    """A catalog localization from one .stringsdict entry."""
    fmt = entry.get("NSStringLocalizedFormatKey", "")
    variables = VARIABLE.findall(fmt)
    whole = VARIABLE.fullmatch(fmt)
    if whole and isinstance(entry.get(whole.group(2)), dict):
        return {"variations": plural_variations(entry[whole.group(2)])}
    substitutions = {}
    for position, (number, name) in enumerate(variables, 1):
        rule = entry.get(name, {})
        substitutions[name] = {"argNum": int(number) if number else position,
                               "formatSpecifier": rule.get("NSStringFormatValueTypeKey", "lld"),
                               "variations": plural_variations(rule)}
    value = VARIABLE.sub(lambda m: f"%{m.group(1) + '$' if m.group(1) else ''}#@{m.group(2)}@", fmt)
    return {"stringUnit": {"state": "translated", "value": value}, "substitutions": substitutions}


def english_sources() -> dict:
    """{table: {key: English}}: what the app shows in English for each key."""
    en_strings = report.read_strings(report.RES / "en.lproj/Localizable.strings")
    info = report.info_plist_strings()
    return {"Localizable": en_strings, "AppShortcuts": {}, "InfoPlist": info}


def build() -> dict:
    """{table: catalog dict}."""
    locales = ["en"] + report.locales()
    english = english_sources()
    en_plurals = json.loads(PLURALS_EN.read_text(encoding="utf-8")) if PLURALS_EN.exists() else {}
    catalogs = {table: {} for table in TABLES}
    for loc in locales:
        folder = report.RES / f"{loc}.lproj"
        for table in TABLES:
            for key, value in report.read_strings(folder / f"{table}.strings").items():
                entry = catalogs[table].setdefault(key, {"localizations": {}})
                entry["localizations"][loc] = unit(value)
        for key, rule in report.read_stringsdict(folder / "Localizable.stringsdict").items():
            entry = catalogs["Localizable"].setdefault(key, {"localizations": {}})
            entry["localizations"][loc] = from_stringsdict(rule)
    for table, sources in english.items():
        for key, value in sources.items():
            entry = catalogs[table].setdefault(key, {"localizations": {}})
            entry["localizations"].setdefault("en", unit(value))
    for key, forms in en_plurals.items():
        entry = catalogs["Localizable"].setdefault(key, {"localizations": {}})
        entry["localizations"]["en"] = {"variations": plural_variations(forms)}
    for table, entries in catalogs.items():
        for key, entry in entries.items():
            if table == "Localizable" and key.startswith("timbre_"):
                entry["extractionState"] = "manual"
            if table == "InfoPlist":
                entry["extractionState"] = "manual"
    return {table: {"sourceLanguage": "en", "strings": dict(sorted(entries.items())), "version": "1.0"}
            for table, entries in catalogs.items()}


def flatten(localization: dict):
    """A localization back to what the .lproj tables hold: a string, or {form: string} for a plural."""
    if "variations" in localization:
        return {form: v["stringUnit"]["value"] for form, v in localization["variations"]["plural"].items()}
    if "substitutions" in localization:
        return {name: {form: v["stringUnit"]["value"] for form, v in sub["variations"]["plural"].items()}
                for name, sub in localization["substitutions"].items()}
    return localization["stringUnit"]["value"]


def check(catalogs: dict) -> list[str]:
    """Every value of every table survives the conversion."""
    problems = []
    en_plurals = json.loads(PLURALS_EN.read_text(encoding="utf-8")) if PLURALS_EN.exists() else {}
    for loc in ["en"] + report.locales():
        folder = report.RES / f"{loc}.lproj"
        plural_keys = set(report.read_stringsdict(folder / "Localizable.stringsdict"))
        for table in TABLES:
            strings = catalogs[table]["strings"]
            for key, value in report.read_strings(folder / f"{table}.strings").items():
                got = strings.get(key, {}).get("localizations", {}).get(loc)
                # A key in both tables reads from the .stringsdict at run time, as it does from the catalog.
                if (loc == "en" and key in en_plurals) or (table == "Localizable" and key in plural_keys):
                    continue
                if got is None or flatten(got) != value:
                    problems.append(f"{loc} {table}: {key!r} lost or changed")
        for key, rule in report.read_stringsdict(folder / "Localizable.stringsdict").items():
            got = catalogs["Localizable"]["strings"].get(key, {}).get("localizations", {}).get(loc)
            whole = VARIABLE.fullmatch(rule.get("NSStringLocalizedFormatKey", ""))
            want = ({f: t for f, t in rule[whole.group(2)].items() if f in FORMS} if whole else
                    {n: {f: t for f, t in rule.get(n, {}).items() if f in FORMS}
                     for _, n in VARIABLE.findall(rule.get("NSStringLocalizedFormatKey", ""))})
            if got is None or flatten(got) != want:
                problems.append(f"{loc} Localizable.stringsdict: {key!r} lost or changed")
    for key, forms in en_plurals.items():
        arguments = report.SPEC.findall(key)
        # "one" may leave the number out ("Every bar"); every other form keeps the key's format arguments.
        wrong = [form for form, text in forms.items()
                 if form not in FORMS or (report.SPEC.findall(text) != arguments and not (form == "one" and "%" not in text))]
        if not {"one", "other"} <= set(forms) or wrong:
            problems.append(f"plurals-en.json: {key!r} needs one and other forms with the key's format arguments")
    return problems


def dumps(catalog: dict) -> str:
    """JSON as Xcode writes a catalog (two-space indent, " : " separators), so an Xcode save changes little."""
    return json.dumps(catalog, indent=2, ensure_ascii=False, separators=(",", " : ")) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, help="write the catalogs into this folder")
    parser.add_argument("--check", action="store_true", help="verify the round trip; exit 1 on a loss")
    args = parser.parse_args(argv)
    catalogs = build()
    for table, catalog in catalogs.items():
        strings = catalog["strings"]
        plurals = sum(1 for e in strings.values() for l in e["localizations"].values()
                      if "variations" in l or "substitutions" in l)
        locales = {loc for e in strings.values() for loc in e["localizations"]}
        print(f"{table}.xcstrings: {len(strings)} keys, {len(locales)} locales, {plurals} plural localizations")
    if args.out:
        args.out.mkdir(parents=True, exist_ok=True)
        for table, catalog in catalogs.items():
            (args.out / f"{table}.xcstrings").write_text(dumps(catalog), encoding="utf-8")
        print(f"Wrote {len(catalogs)} catalogs to {args.out}")
    if args.check:
        problems = check(catalogs)
        for problem in problems[:40]:
            print("LOST " + problem)
        if problems:
            print(f"FAILED: {len(problems)} values don't survive the conversion")
            return 1
        print("OK: every value of every table survives the conversion")
    return 0


if __name__ == "__main__":
    sys.exit(main())
